/**
 * Frontend view-model types for the Meet overlay.
 * Designed to accept future backend/model payloads without hard-coding Aditi's contract.
 * All demo fixtures must set `source: "demo"`.
 */

export type DataSource = "demo" | "backend";

export type ConfidenceAvailability =
  | { status: "unavailable"; reason: "not_calibrated" | "not_provided" | "demo" }
  | { status: "provided"; value: number; calibrated: boolean; note?: string };

export type DetectionKind =
  | "no_result"
  | "processing"
  | "available"
  | "insufficient_evidence"
  | "model_unavailable"
  | "failed";

export type EvidenceCategory =
  | "detection"
  | "audio_linguistic"
  | "recording_quality";

export interface InterviewSession {
  id: string;
  title: string;
  meetContext: string;
  source: DataSource;
  /** Demo vs offline/backend-shaped analysis — never conflate the two. */
  modeLabel: "DEMO SIMULATION" | "OFFLINE ANALYSIS";
}

export interface InterviewQuestion {
  id: string;
  text: string;
  askedAtLabel?: string;
}

export interface TranscriptSegment {
  id: string;
  speaker: "Interviewer" | "Candidate" | string;
  startSeconds: number;
  text: string;
}

export interface SupportingEvidence {
  id: string;
  category: EvidenceCategory;
  title: string;
  description: string;
  /** Aligns with backend EvidenceSignal.signal_name when known. */
  signalName?: string;
  modality?: "audio" | "transcript" | "visual" | "recording" | "processing";
  qualityStatus?: "ok" | "warning" | "unusable" | "unknown";
}

export interface QualityWarning {
  id: string;
  code: string;
  message: string;
}

export interface SuggestedFollowUp {
  id: string;
  text: string;
  sourceLabel: "Sample follow-up — not generated by a live AI model.";
}

export interface DetectionPrediction {
  schemaVersion: string;
  /** Human-review oriented label — never "cheating confirmed". */
  reviewLabel: string;
  reviewStatus: "Requires review" | "No elevated signal" | "Insufficient evidence";
  /** Raw model score placeholder; must not be shown as cheating probability. */
  rawScore: number | null;
  confidence: ConfidenceAvailability;
  evidence: SupportingEvidence[];
  relatedQuestionId: string;
  model: { name: string; version: string; note: string };
  warnings: string[];
}

export type DetectionResultState =
  | { kind: "no_result" }
  | { kind: "processing"; message: string }
  | { kind: "available"; prediction: DetectionPrediction }
  | { kind: "insufficient_evidence"; message: string }
  | { kind: "model_unavailable"; message: string }
  | { kind: "failed"; message: string };

export type DemoTimelineEvent =
  | { atMs: number; type: "show_question" }
  | { atMs: number; type: "candidate_responding" }
  | { atMs: number; type: "transcript_segment"; segmentIndex: number }
  | { atMs: number; type: "analysis_processing" }
  | { atMs: number; type: "analysis_result" }
  | { atMs: number; type: "show_followup" }
  | { atMs: number; type: "scenario_complete" };

export interface DemoScenario {
  id: string;
  title: string;
  kind: "ordinary" | "possible_ai_indicators";
  summary: string;
  question: InterviewQuestion;
  transcript: TranscriptSegment[];
  detectionWhenReady: DetectionResultState;
  followup: SuggestedFollowUp;
  qualityWarnings: QualityWarning[];
  timeline: DemoTimelineEvent[];
}
